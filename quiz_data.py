def profile_vec(code):
    v = {d: 0.0 for d in DIMS}
    for w, ch in zip((3, 2, 1), code):
        v[ch] = w
    n = sum(x * x for x in v.values()) ** 0.5
    return {d: x / n for d, x in v.items()}

def match_classes(user_scores, top=6):
    """user_scores: {R:int,...} 原始分(每维 0-12)。返回 [(mclass,code,score0-100)]"""
    n = sum(x * x for x in user_scores.values()) ** 0.5 or 1
    u = {d: user_scores.get(d, 0) / n for d in DIMS}
    out = []
    for mc, code in CLASS_RIASEC.items():
        p = profile_vec(code)
        cos = sum(u[d] * p[d] for d in DIMS)
        out.append((mc, code, round(cos * 100)))
    out.sort(key=lambda x: -x[2])
    return out[:top]
